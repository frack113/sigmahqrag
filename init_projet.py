def create_data_structure() -> None:
    for d in DATA_DIRS:
        try:
            Path(d).mkdir(parents=True, exist_ok=True)
        except (PermissionError, OSError) as e:
            console.print(f"[red]✗[/] Failed to create directory {d}: {e}")
            sys.exit(1)


def create_config_file(content: str | None = None) -> None:
    if not CONFIG_FILE.exists():
        CONFIG_FILE.write_text(content or DEFAULT_TOML, encoding="utf-8")


def clone_or_update_sigma_spec() -> None:
    if SIGMA_SPEC_DIR.exists():
        try:
            repo = git.Repo(SIGMA_SPEC_DIR)
            if repo.is_dirty():
                repo.git.stash()
            repo.remotes.origin.pull()
        except GitCommandError:
            try:
                repo = git.Repo(SIGMA_SPEC_DIR)
                repo.remotes.origin.fetch()
                repo.git.reset("--hard", f"origin/{SIGMA_SPEC_REF}")
            except GitCommandError as e2:
                console.print(f"[red]✗[/] Failed to update sigma-specification: {e2}")
                sys.exit(1)
    else:
        SIGMA_SPEC_DIR.parent.mkdir(parents=True, exist_ok=True)
        max_retries = 3
        for attempt in range(1, max_retries + 1):
            try:
                with tempfile.TemporaryDirectory(prefix="sigma-spec-") as tmp:
                    temp_dir = Path(tmp) / "sigma-specification"
                    git.Repo.clone_from(SIGMA_SPEC_REPO, temp_dir, branch=SIGMA_SPEC_REF)
                    if SIGMA_SPEC_DIR.exists():
                        shutil.rmtree(SIGMA_SPEC_DIR)
                    shutil.move(str(temp_dir), str(SIGMA_SPEC_DIR))
                break
            except GitCommandError as e:
                if attempt == max_retries:
                    console.print(
                        f"[red]✗[/] Failed to clone sigma-specification "
                        f"after {max_retries} attempts: {e}"
                    )
                    sys.exit(1)
                time.sleep(2 * attempt)
            except OSError as e:
                console.print(f"[red]✗[/] Failed to move cloned repository: {e}")
                sys.exit(1)


def initialize_database(db_service: Optional[DatabaseServiceProtocol] = None) -> None:
    from src.infrastructure.database import DatabaseService

    db = db_service or DatabaseService()
    db.initialize()

    tables = frozenset(db.get_tables())
    missing = EXPECTED_TABLES - tables
    if missing:
        console.print(f"[red]✗[/] Missing tables after init: {sorted(missing)}")
        sys.exit(1)

    try:
        db.set_config("schema_version", SCHEMA_VERSION)
    except Exception as e:
        console.print(f"[red]✗[/] Failed to set schema version: {e}")
        sys.exit(1)


def run_initial_workers() -> None:
    dispatcher: TaskDispatcher | None = None
    try:
        dispatcher = TaskDispatcher(poll_interval=1, max_workers=4)
        dispatcher.start()

        dispatcher.ask_for_worker(
            WorkerName.MODEL_SYNC,
            llm_dir=str(LLM_DIR),
            embeddings_dir=str(EMBEDDINGS_DIR),
        )
        dispatcher.ask_for_worker(WorkerName.LOCAL_REPO_SYNC)

        _wait_for_initial_workers(dispatcher)
    except KeyboardInterrupt:
        console.print("\n[red]✗[/] Initialization interrupted by user.")
        sys.exit(130)
    finally:
        if dispatcher is not None:
            dispatcher.stop()

    _sync_model_registry_to_db()


def _wait_for_initial_workers(dispatcher: TaskDispatcher) -> None:
    max_wait = 300
    poll_interval = 2
    start_time = time.time()

    with Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        TaskProgressColumn(),
        TimeElapsedColumn(),
        console=console,
    ) as progress:
        model_task = progress.add_task("[yellow]ModelSyncWorker[/]", total=None)
        repo_task = progress.add_task("[yellow]LocalRepoSyncWorker[/]", total=None)

        while time.time() - start_time < max_wait:
            model_progress_data = dispatcher.get_worker_progress(WorkerName.MODEL_SYNC.value)
            repo_progress_data = dispatcher.get_worker_progress(WorkerName.LOCAL_REPO_SYNC.value)

            model_status = model_progress_data.get("status") if model_progress_data else None
            repo_status = repo_progress_data.get("status") if repo_progress_data else None

            errors: list[str] = []
            if model_status == WorkerStatus.ERROR.value:
                errors.append("ModelSyncWorker ended with ERROR")
            if repo_status == WorkerStatus.ERROR.value:
                errors.append("LocalRepoSyncWorker ended with ERROR")
            if errors:
                for msg in errors:
                    console.print(f"[red]✗[/] {msg}")
                sys.exit(1)

            if model_status == WorkerStatus.IDLE.value:
                progress.update(model_task, completed=100, total=100)
            if repo_status == WorkerStatus.IDLE.value:
                progress.update(repo_task, completed=100, total=100)
            if model_status == WorkerStatus.IDLE.value and repo_status == WorkerStatus.IDLE.value:
                return

            time.sleep(poll_interval)

        console.print(f"[red]✗[/] Timeout ({max_wait}s) waiting for initial workers")
        sys.exit(1)


def _sync_model_registry_to_db() -> None:
    try:
        from src.back.models.registry import UnifiedRegistry
        from src.infrastructure.database import DatabaseService

        db = DatabaseService.get_instance()
        reg = UnifiedRegistry.get_instance()
        reg.sync_llm_folder(LLM_DIR, db)
        reg.sync_embeddings_folder(EMBEDDINGS_DIR, db)
    except Exception as e:
        console.print(f"[yellow]⚠[/] Model registry sync failed: {e}")


