def _interactive_config() -> dict:
    cfg: dict = {}

    console.print(
        Panel.fit(
            "[bold]LLM Service[/]\nConfigure your llama.cpp-compatible server.",
            border_style="blue",
        )
    )
    cfg["llama_url"] = Prompt.ask("Base URL", default=DEFAULT_LLAMA_BASE_URL)
    cfg["llama_internal"] = Confirm.ask("Manage internally (auto-start/stop)?", default=False)

    console.print(
        Panel.fit(
            "[bold]Qdrant Service[/]\nConfigure the vector database.",
            border_style="blue",
        )
    )
    cfg["qdrant_url"] = Prompt.ask("Base URL", default=DEFAULT_QDRANT_BASE_URL)
    cfg["qdrant_internal"] = Confirm.ask("Manage internally (auto-start/stop)?", default=False)
    cfg["qdrant_collection"] = Prompt.ask("Collection name", default=DEFAULT_QDRANT_COLLECTION)
    cfg["qdrant_vector_size"] = IntPrompt.ask("Vector size", default=DEFAULT_QDRANT_VECTOR_SIZE)

    console.print(
        Panel.fit(
            "[bold]Logging[/]\nSet the logging verbosity.",
            border_style="blue",
        )
    )
    cfg["log_level"] = Prompt.ask(
        "Log level",
        choices=["DEBUG", "INFO", "WARNING", "ERROR"],
        default="INFO",
    )

    console.print(
        Panel.fit(
            "[bold]Hardware[/]\nOS and GPU configuration.",
            border_style="blue",
        )
    )
    cfg["os"] = Prompt.ask(
        "Operating system",
        choices=["windows", "linux", "macos"],
        default="windows",
    )
    cfg["gpu"] = Prompt.ask(
        "GPU acceleration",
        choices=["cpu", "vulkan", "cuda"],
        default="vulkan",
    )

    return cfg


def _print_config_summary(cfg: dict) -> None:
    table = Table.grid(padding=(0, 2))
    table.add_column(style="bold yellow")
    table.add_column(style="white")

    table.add_row("LLM URL", cfg.get("llama_url", ""))
    table.add_row("LLM Internal", str(cfg.get("llama_internal", False)))
    table.add_row("Qdrant URL", cfg.get("qdrant_url", ""))
    table.add_row("Qdrant Internal", str(cfg.get("qdrant_internal", False)))
    table.add_row("Collection", cfg.get("qdrant_collection", ""))
    table.add_row("Vector Size", str(cfg.get("qdrant_vector_size", 0)))
    table.add_row("Log Level", cfg.get("log_level", ""))
    table.add_row("OS", cfg.get("os", ""))
    table.add_row("GPU", cfg.get("gpu", ""))

    console.print(
        Panel.fit(
            table,
            title="[bold]Configuration Summary[/]",
            border_style="green",
        )
    )


# ── Entry points ──


def run_tui() -> None:
    """Full interactive TUI flow."""
    _show_welcome()

    cfg = _interactive_config()

    console.print()
    _print_config_summary(cfg)

    if not Confirm.ask("\n[bold]Proceed with initialization?[/]", default=True):
        console.print("[yellow]Aborted by user.[/]")
        sys.exit(0)

    console.print()
    with Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        TaskProgressColumn(),
        TimeElapsedColumn(),
        console=console,
    ) as progress:
        task_dirs = progress.add_task("[cyan]Creating data directories...[/]", total=None)
        create_data_structure()
        progress.update(task_dirs, completed=100, total=100)

        task_config = progress.add_task("[cyan]Writing configuration...[/]", total=None)
        toml_content = _generate_custom_toml(cfg)
        create_config_file(content=toml_content)
        progress.update(task_config, completed=100, total=100)

        task_sigma = progress.add_task("[cyan]Cloning sigma-specification...[/]", total=None)
        clone_or_update_sigma_spec()
        progress.update(task_sigma, completed=100, total=100)

        task_db = progress.add_task("[cyan]Initializing DuckDB...[/]", total=None)
        initialize_database()
        progress.update(task_db, completed=100, total=100)

    console.print()
    with Progress(
        SpinnerColumn(),
        TextColumn("[progress.description]{task.description}"),
        BarColumn(),
        TaskProgressColumn(),
        TimeElapsedColumn(),
        console=console,
    ) as progress:
        task_workers = progress.add_task("[cyan]Running initial workers...[/]", total=None)
        run_initial_workers()
        progress.update(task_workers, completed=100, total=100)

    from src.infrastructure.database import DatabaseService

    try:
        db = DatabaseService.get_instance()
        db.persist()
        db.close()
    except RuntimeError:
        pass

    console.print()
    console.print(
        Panel.fit(
            "[bold green]✓ Initialization complete![/]\n\n"
            "  [dim]Review/edit [white]sigmarag.toml[/] as needed\n"
            "  Then run [white]uv run main.py[/] to start the server[/]",
            border_style="green",
        )
    )


def run_defaults() -> None:
    """Non-interactive mode with default configuration (for CI / tests)."""
    from src.infrastructure.database import DatabaseService

    create_data_structure()
    create_config_file()
    clone_or_update_sigma_spec()
    initialize_database()
    run_initial_workers()

    try:
        db = DatabaseService.get_instance()
        db.persist()
        db.close()
    except RuntimeError:
        pass


def main() -> None:
    if "--defaults" in sys.argv[1:]:
        run_defaults()
    else:
        try:
            run_tui()
        except (EOFError, KeyboardInterrupt):
            console.print("\n[yellow]Aborted by user.[/]")
            sys.exit(0)


if __name__ == "__main__":
    main()
