def _render_step_bar(current_step: int, total_steps: int) -> Panel:
    segments = []
    for i in range(total_steps):
        if i < current_step:
            segments.append(Text("✓", style="green"))
        elif i == current_step:
            segments.append(Text("►", style="cyan bold"))
        else:
            segments.append(Text("○", style="dim"))

    bar = " ".join(segments)
    return Panel(
        bar,
        title="[dim]Steps[/]",
        title_align="left",
        border_style="cyan",
        padding=(0, 1),
    )


