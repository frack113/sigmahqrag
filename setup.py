def _interactive_tui() -> dict:
    """Full-screen installer TUI with step-by-step navigation."""
    from src.config.constants import (
        DEFAULT_LLAMA_BASE_URL,
        DEFAULT_LLAMA_MANAGE,
        DEFAULT_QDRANT_BASE_URL,
        DEFAULT_QDRANT_MANAGE,
        DEFAULT_QDRANT_COLLECTION,
        DEFAULT_QDRANT_VECTOR_SIZE,
    )

    cfg: dict = {
        "llama_url": DEFAULT_LLAMA_BASE_URL,
        "llama_internal": DEFAULT_LLAMA_MANAGE,
        "qdrant_url": DEFAULT_QDRANT_BASE_URL,
        "qdrant_internal": DEFAULT_QDRANT_MANAGE,
        "qdrant_collection": DEFAULT_QDRANT_COLLECTION,
        "qdrant_vector_size": DEFAULT_QDRANT_VECTOR_SIZE,
        "log_level": "INFO",
        "os": "windows",
        "gpu": "vulkan",
    }

    console.clear()
    console.print(
        Panel(
            "[bold cyan]SigmaHQ RAG[/] — Setup\n"
            "[dim]Use ↑↓ to navigate, Tab for next field, Space to toggle, Enter to confirm[/]",
            border_style="cyan",
            padding=(1, 2),
        )
    )

    current_step = 0
    current_field = 0

    while True:
        console.clear()
        console.print(_render_step_bar(current_step, len(STEPS)))
        console.print()

        if current_step == len(STEPS):
            # Review step
            console.print(_render_right_panel(current_step, cfg, show_preview=True))
            decision = Prompt.ask(
                "\n[bold]Proceed with initialization?[/]", default=True, choices=["y", "n"]
            )
            if decision == "n":
                console.print("[yellow]Aborted by user.[/]")
                sys.exit(0)
            break

        step_fields = STEPS[current_step]
        step_name = step_fields[0]

        if current_field == 0:
            # First field of this step
            if step_name == "LLM Service":
                cfg["llama_url"] = Prompt.ask("LLM Base URL", default=cfg["llama_url"])
            elif step_name == "Qdrant Service":
                cfg["qdrant_url"] = Prompt.ask("Qdrant Base URL", default=cfg["qdrant_url"])
            elif step_name == "Logging":
                cfg["log_level"] = Prompt.ask(
                    "Log level",
                    choices=["DEBUG", "INFO", "WARNING", "ERROR"],
                    default=cfg["log_level"],
                )
            elif step_name == "Hardware":
                cfg["os"] = Prompt.ask(
                    "Operating system",
                    choices=["windows", "linux", "macos"],
                    default=cfg["os"],
                )

        elif current_field == 1:
            if step_name == "LLM Service":
                cfg["llama_internal"] = Confirm.ask(
                    "Manage internally?", default=cfg["llama_internal"]
                )
            elif step_name == "Qdrant Service":
                cfg["qdrant_internal"] = Confirm.ask(
                    "Manage internally?", default=cfg["qdrant_internal"]
                )
            elif step_name == "Hardware":
                cfg["gpu"] = Prompt.ask(
                    "GPU acceleration",
                    choices=["cpu", "vulkan", "cuda"],
                    default=cfg["gpu"],
                )

        elif current_field == 2:
            if step_name == "Qdrant Service":
                cfg["qdrant_collection"] = Prompt.ask(
                    "Collection name", default=cfg["qdrant_collection"]
                )

        elif current_field == 3:
            if step_name == "Qdrant Service":
                cfg["qdrant_vector_size"] = IntPrompt.ask(
                    "Vector size", default=cfg["qdrant_vector_size"]
                )

        current_field += 1

        if current_field >= len(step_fields):
            current_field = 0
            current_step += 1

    return cfg


