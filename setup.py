def create_data_structure() -> None:
    for d in DATA_DIRS:
        try:
            Path(d).mkdir(parents=True, exist_ok=True)
        except (PermissionError, OSError) as e:
            console.print(f"[red]✗[/] Failed to create directory {d}: {e}")
